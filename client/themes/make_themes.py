"""Generate the C4Script color themes of the extension.

- "C4Script Dark (C#)" and "C4Script Dark (C++)": VS Code's Dark+ (dark_vs.json + dark_plus.json, MIT License,
  Copyright (c) Microsoft Corporation) with C4Script semantic token colors on top. The C4Script colors use
  language-qualified selectors (`keyword:c4script`), so other languages look exactly like in Dark+.
  C#: like VS Code's C# (Dark+): control keywords purple, everything else as in C# with types (int, object) teal.
  C++: like VS Code's C/C++ (Dark+): built-in types blue (storage.type), #strict/#include/#appendto purple
  (keyword.control.directive), $Name$ blue (macro use), nullptr/this blue.
- "C4Scripter Classic" (c4scripter-color-theme.json) is written by hand: the colors of Clonk-Karl's C4Scripter.

Usage: python client/themes/make_themes.py ["C:/Program Files/Microsoft VS Code/<hash>/resources/app/extensions/theme-defaults/themes"]
"""
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def find_theme_dir():
    if len(sys.argv) > 1:
        return sys.argv[1]
    hits = glob.glob(r"C:/Program Files/Microsoft VS Code/*/resources/app/extensions/theme-defaults/themes")
    hits += glob.glob(os.path.expandvars(r"%LOCALAPPDATA%/Programs/Microsoft VS Code/*/resources/app/extensions/theme-defaults/themes"))
    if not hits:
        sys.exit("VS Code's theme-defaults/themes folder not found: pass it as argument")
    return hits[0]


def load(path):
    s = open(path, encoding="utf-8").read()
    s = re.sub(r"^\s*//.*$", "", s, flags=re.M)
    s = re.sub(r",(\s*[}\]])", r"\1", s)
    return json.loads(s)


def dark_plus(theme_dir):
    vs = load(os.path.join(theme_dir, "dark_vs.json"))
    plus = load(os.path.join(theme_dir, "dark_plus.json"))
    colors = dict(vs.get("colors", {}))
    colors.update(plus.get("colors", {}))
    tokens = vs.get("tokenColors", []) + plus.get("tokenColors", [])
    semantic = dict(vs.get("semanticTokenColors", {}))
    semantic.update(plus.get("semanticTokenColors", {}))
    return colors, tokens, semantic


# Dark+ palette
BLUE, PURPLE, LIGHTBLUE, CONST, TEAL, YELLOW = "#569CD6", "#C586C0", "#9CDCFE", "#4FC1FF", "#4EC9B0", "#DCDCAA"
STRING, NUMBER, COMMENT, ESCAPE = "#CE9178", "#B5CEA8", "#6A9955", "#D7BA7D"

COMMON = {
    "comment": COMMENT,
    "string": STRING,
    "formatPlaceholder": LIGHTBLUE,
    "stringEscape": ESCAPE,
    "number": NUMBER,
    "keyword": BLUE,
    "controlKeyword": PURPLE,
    "thisKeyword": BLUE,
    "bool": BLUE,
    "method": YELLOW,
    "method.defaultLibrary": YELLOW,
    "parameter": LIGHTBLUE,
    "variable": LIGHTBLUE,
    "property": LIGHTBLUE,
    "enumMember": CONST,
    "id": TEAL,
}
STYLES = {
    "csharp": ("C4Script Dark (C#)", {**COMMON, "parameterType": TEAL, "macro": BLUE, "translation": CONST}),
    "cpp": ("C4Script Dark (C++)", {**COMMON, "parameterType": BLUE, "macro": PURPLE, "translation": BLUE}),
}


def main():
    theme_dir = find_theme_dir()
    colors, tokens, semantic = dark_plus(theme_dir)
    for key, (name, c4) in STYLES.items():
        sem = dict(semantic)
        for sel, col in c4.items():
            sem[f"{sel}:c4script"] = col
        theme = {
            "$schema": "vscode://schemas/color-theme",
            "name": name,
            "type": "dark",
            "semanticHighlighting": True,
            "colors": colors,
            "tokenColors": tokens,
            "semanticTokenColors": sem,
        }
        out = os.path.join(HERE, f"c4script-{key}-dark-color-theme.json")
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write("// Generated by make_themes.py from VS Code's Dark+ theme (MIT License, Copyright (c) Microsoft\n")
            f.write("// Corporation) plus C4Script semantic token colors. Do not edit: change make_themes.py.\n")
            json.dump(theme, f, indent=2)
            f.write("\n")
        print("written", out)


if __name__ == "__main__":
    main()
